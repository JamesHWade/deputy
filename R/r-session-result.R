r_session_result <- function(
  code,
  segments,
  session_id,
  execution_id,
  generation,
  fresh,
  reset_reason,
  outcome
) {
  values <- list()
  html <- list()
  if (fresh) {
    text <- paste0(
      "Started a fresh R session (generation ",
      generation,
      "). ",
      if (!is.null(reset_reason)) {
        paste0("Previous session: ", reset_reason, ". ")
      },
      "Only objects created in this session are available."
    )
    values <- list(ellmer::ContentText(text))
    html <- list(paste0("<p>", htmltools::htmlEscape(text), "</p>"))
  }
  image_uri <- function(bytes) {
    paste0(
      "data:image/png;base64,",
      gsub("[\r\n]", "", jsonlite::base64_enc(bytes))
    )
  }
  for (segment in segments) {
    if (identical(segment$type, "plot")) {
      uri <- image_uri(segment$data)
      values[[length(values) + 1L]] <- ellmer::content_image_url(uri)
      html[[length(html) + 1L]] <- paste0(
        '<img src="',
        uri,
        '" alt="Plot generated by the R code in Details." style="max-width:100%;height:auto;"/>'
      )
    } else if (identical(segment$type, "artifact")) {
      text <- segment$text
      if (is.null(segment$png)) {
        text <- paste(text, segment$artifact$fallback, sep = "\n")
      }
      values[[length(values) + 1L]] <- ellmer::ContentText(text)
      html[[length(html) + 1L]] <- paste0(
        "<pre>",
        htmltools::htmlEscape(text),
        "</pre>"
      )
      if (!is.null(segment$png)) {
        preview <- image_uri(segment$png)
        values[[length(values) + 1L]] <- ellmer::content_image_url(preview)
        html[[length(html) + 1L]] <- paste0(
          '<img src="',
          preview,
          '" alt="Static preview of the interactive R result." style="max-width:100%;height:auto;"/>'
        )
      }
      if (!is.null(segment$artifact$id)) {
        html[[length(html) + 1L]] <- htmltools::renderTags(
          htmltools::tags$p(
            "Interactive R result saved.",
            `data-deputy-r-artifact` = segment$artifact$id
          )
        )$html
      }
    } else {
      text <- paste0(
        if (!identical(segment$type, "text")) paste0(segment$type, ": "),
        segment$text
      )
      values[[length(values) + 1L]] <- ellmer::ContentText(text)
      html[[length(html) + 1L]] <- paste0(
        "<pre>",
        htmltools::htmlEscape(text),
        "</pre>"
      )
    }
  }
  if (!length(segments)) {
    text <- "Code ran without printed output."
    values[[length(values) + 1L]] <- ellmer::ContentText(text)
    html[[length(html) + 1L]] <- paste0("<p>", text, "</p>")
  }
  display <- list(
    title = "R calculation and plots",
    open = TRUE,
    show_request = FALSE,
    html = htmltools::HTML(paste0(
      '<div class="deputy-r-result"><details><summary>Details: R code</summary><pre><code>',
      htmltools::htmlEscape(code),
      "</code></pre></details>",
      paste(unlist(html), collapse = "\n"),
      "</div>"
    ))
  )
  ellmer::ContentToolResult(
    value = values,
    extra = list(
      display = display,
      deputy_r = list(
        schema_version = 1L,
        code = code,
        session_id = session_id,
        execution_id = execution_id,
        generation = generation,
        fresh = fresh,
        reset_reason = reset_reason,
        outcome = outcome,
        segments = segments
      )
    )
  )
}
