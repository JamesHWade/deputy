r_session_result <- function(
  code,
  segments,
  session_id,
  execution_id,
  generation,
  fresh,
  reset_reason,
  outcome
) {
  values <- list()
  html <- list()
  if (fresh) {
    text <- paste0(
      "Started a fresh R session (generation ",
      generation,
      "). ",
      if (!is.null(reset_reason)) {
        paste0("Previous session: ", reset_reason, ". ")
      },
      "Only objects created in this session are available."
    )
    values <- list(ellmer::ContentText(text))
    html <- list(paste0("<p>", htmltools::htmlEscape(text), "</p>"))
  }
  for (segment in segments) {
    if (identical(segment$type, "plot")) {
      uri <- paste0(
        "data:image/png;base64,",
        jsonlite::base64_enc(segment$data)
      )
      values[[length(values) + 1L]] <- ellmer::content_image_url(uri)
      html[[length(html) + 1L]] <- paste0(
        '<img src="',
        uri,
        '" alt="Plot generated by the R code in Details." style="max-width:100%;height:auto;"/>'
      )
    } else {
      text <- paste0(
        if (!identical(segment$type, "text")) paste0(segment$type, ": "),
        segment$text
      )
      values[[length(values) + 1L]] <- ellmer::ContentText(text)
      html[[length(html) + 1L]] <- paste0(
        "<pre>",
        htmltools::htmlEscape(text),
        "</pre>"
      )
    }
  }
  if (!length(segments)) {
    values[[length(values) + 1L]] <- ellmer::ContentText(
      "Code ran without printed output."
    )
  }
  display <- list(
    title = "R calculation and plots",
    open = TRUE,
    show_request = FALSE,
    html = htmltools::HTML(paste0(
      '<div class="deputy-r-result"><details><summary>Details: R code</summary><pre><code>',
      htmltools::htmlEscape(code),
      "</code></pre></details>",
      paste(unlist(html), collapse = "\n"),
      "</div>"
    ))
  )
  if (requireNamespace("shinychat", quietly = TRUE)) {
    display <- do.call(shinychat::tool_result_display, display)
  }
  ellmer::ContentToolResult(
    value = values,
    extra = list(
      display = display,
      deputy_r = list(
        schema_version = 1L,
        code = code,
        session_id = session_id,
        execution_id = execution_id,
        generation = generation,
        fresh = fresh,
        reset_reason = reset_reason,
        outcome = outcome,
        segments = segments
      )
    )
  )
}
